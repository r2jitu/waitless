fn push_data_frames(c: &mut ProxyConn, data: &[u8], mac: &[u8; 6], ring: &SpscRing<256>) {
    let mut off = 0;
    while off < data.len() {
        let chunk = (data.len() - off).min(1460);
        let frame = build_tcp_frame(
            mac, GW_IP, VM_IP, c.src_port, 80,
            c.my_seq, c.peer_ack, 0x18, &data[off..off + chunk],
        );
        c.my_seq = c.my_seq.wrapping_add(chunk as u32);
        off += chunk;
        ring.push(&frame);
    }
}

fn build_grat_arp(guest_mac: &[u8; 6]) -> Vec<u8> {
    let mut arp = Vec::with_capacity(VIRTIO_NET_HDR_SIZE + 14 + 28);
    arp.extend_from_slice(&[0u8; VIRTIO_NET_HDR_SIZE]);
    arp.extend_from_slice(&[0xff; 6]);
    arp.extend_from_slice(&GW_MAC);
    arp.extend_from_slice(&0x0806u16.to_be_bytes());
    arp.extend_from_slice(&1u16.to_be_bytes());
    arp.extend_from_slice(&0x0800u16.to_be_bytes());
    arp.push(6); arp.push(4);
    arp.extend_from_slice(&2u16.to_be_bytes());
    arp.extend_from_slice(&GW_MAC);
    arp.extend_from_slice(&GW_IP);
    arp.extend_from_slice(guest_mac);
    arp.extend_from_slice(&GW_IP);
    arp
}

fn build_tcp_frame(
    dst_mac: &[u8; 6], src_ip: [u8; 4], dst_ip: [u8; 4],
    src_port: u16, dst_port: u16, seq: u32, ack: u32,
    flags: u8, payload: &[u8],
) -> Vec<u8> {
    let tcp_len = 20 + payload.len();
    let ip_total = 20 + tcp_len;
    let mut pkt = Vec::with_capacity(VIRTIO_NET_HDR_SIZE + 14 + ip_total);

    pkt.extend_from_slice(&[0u8; VIRTIO_NET_HDR_SIZE]);
    pkt.extend_from_slice(dst_mac);
    pkt.extend_from_slice(&GW_MAC);
    pkt.extend_from_slice(&0x0800u16.to_be_bytes());

    let ip_start = pkt.len();
    pkt.push(0x45); pkt.push(0);
    pkt.extend_from_slice(&(ip_total as u16).to_be_bytes());
    pkt.extend_from_slice(&[0, 0, 0x40, 0]);
    pkt.push(64); pkt.push(6);
    pkt.extend_from_slice(&[0, 0]);
    pkt.extend_from_slice(&src_ip);
    pkt.extend_from_slice(&dst_ip);
    let cksum = ipv4_checksum(&pkt[ip_start..ip_start + 20]);
    pkt[ip_start + 10] = (cksum >> 8) as u8;
    pkt[ip_start + 11] = (cksum & 0xff) as u8;

    let tcp_start = pkt.len();
    pkt.extend_from_slice(&src_port.to_be_bytes());
    pkt.extend_from_slice(&dst_port.to_be_bytes());
    pkt.extend_from_slice(&seq.to_be_bytes());
    pkt.extend_from_slice(&ack.to_be_bytes());
    pkt.push(0x50); pkt.push(flags);
    pkt.extend_from_slice(&0xffffu16.to_be_bytes());
    pkt.extend_from_slice(&[0, 0, 0, 0]);
    pkt.extend_from_slice(payload);
    let tcp_cksum = tcp_checksum(&src_ip, &dst_ip, &pkt[tcp_start..]);
    pkt[tcp_start + 16] = (tcp_cksum >> 8) as u8;
    pkt[tcp_start + 17] = (tcp_cksum & 0xff) as u8;

    pkt
}

fn ipv4_checksum(hdr: &[u8]) -> u16 {
    let mut s: u32 = 0;
    let mut i = 0;
    while i + 1 < hdr.len() { s += ((hdr[i] as u32) << 8) | hdr[i+1] as u32; i += 2; }
    if i < hdr.len() { s += (hdr[i] as u32) << 8; }
    while s >> 16 != 0 { s = (s & 0xffff) + (s >> 16); }
    !(s as u16)
}

fn tcp_checksum(src_ip: &[u8; 4], dst_ip: &[u8; 4], seg: &[u8]) -> u16 {
    let mut s: u32 = 0;
    s += ((src_ip[0] as u32) << 8) | src_ip[1] as u32;
    s += ((src_ip[2] as u32) << 8) | src_ip[3] as u32;
    s += ((dst_ip[0] as u32) << 8) | dst_ip[1] as u32;
    s += ((dst_ip[2] as u32) << 8) | dst_ip[3] as u32;
    s += 6;
    s += seg.len() as u32;
    let mut i = 0;
    while i + 1 < seg.len() { s += ((seg[i] as u32) << 8) | seg[i+1] as u32; i += 2; }
    if i < seg.len() { s += (seg[i] as u32) << 8; }
    while s >> 16 != 0 { s = (s & 0xffff) + (s >> 16); }
    !(s as u16)
}
